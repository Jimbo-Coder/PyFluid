def write_catalog(
    ids_header: Path,
    catalog_header: Path,
    diagnostic_header: Path,
    method_header: Path,
    json_path: Path,
    markdown_path: Path,
    latex_path: Path,
) -> None:
    _write_if_changed(ids_header, render_field_ids_header())
    _write_if_changed(catalog_header, render_field_catalog_header())
    _write_if_changed(diagnostic_header, render_diagnostic_catalog_header())
    _write_if_changed(method_header, render_method_catalog_header())
    _write_if_changed(json_path, render_field_catalog_json())
    _write_if_changed(markdown_path, render_equation_markdown())
    _write_if_changed(latex_path, render_equation_latex())
