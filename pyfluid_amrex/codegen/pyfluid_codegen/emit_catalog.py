def _write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == content:
        return
    path.write_text(content)


def _cpp_string(value: str) -> str:
    return json.dumps(value)


def _flatten(fields: tuple[GridField, ...]) -> tuple[FieldComponent, ...]:
    return tuple(component for field in fields for component in field.components)


def render_field_ids_header() -> str:
    fluid_components = _flatten(FLUID_NEWTONIAN_FIELDS)
    magnetic_components = MAGNETIC_FIELD.components
    z4c_components = _flatten(Z4C_FIELDS)

    conserved_lines = [
        f"   {component.cpp_id} = {index},"
        for index, component in enumerate(fluid_components)
    ]
    conserved_lines.append(f"   NVAR_HYDRO = {len(fluid_components)},")
    conserved_lines.extend(
        f"   {component.cpp_id} = {len(fluid_components) + index},"
        for index, component in enumerate(magnetic_components)
    )
    conserved_lines.append(
        f"   NVAR_MHD = {len(fluid_components) + len(magnetic_components)},"
    )
    z4c_lines = [
        f"   {component.cpp_id} = {index},"
        for index, component in enumerate(z4c_components)
    ]
    z4c_lines.append(f"   Z4C_NUM_COMPONENTS = {len(z4c_components)},")
    aux_lines = [f"   {field.aux_id}," for field in AUXILIARY_FIELDS]
    aux_lines.append("   Unknown,")

    def component_array(name: str, fields: tuple[GridField, ...]) -> str:
        ids = ",\n".join(
            f"   {component.cpp_id}" for component in _flatten(fields)
        )
        return (
            f"inline constexpr int {name}[{len(_flatten(fields))}] = {{\n"
            f"{ids},\n"
            "};"
        )

    return "\n".join(
        (
            "// Generated by pyfluid_codegen.field_catalog. Do not edit.",
            "#pragma once",
            "",
            "namespace pyfluid_amrex {",
            "",
            "enum Conserved {",
            *conserved_lines,
            "};",
            "",
            "enum Z4cComponent : int {",
            *z4c_lines,
            "};",
            "",
            component_array("Z4C_GAMMA_TILDE_COMPONENTS", (Z4C_FIELDS[1],)),
            "",
            component_array("Z4C_A_TILDE_COMPONENTS", (Z4C_FIELDS[3],)),
            "",
            component_array("Z4C_GAMMA_TILDE_VECTOR_COMPONENTS", (Z4C_FIELDS[4],)),
            "",
            component_array("Z4C_SHIFT_COMPONENTS", (Z4C_FIELDS[7],)),
            "",
            "enum class AuxGridField {",
            *aux_lines,
            "};",
            "",
            "} // namespace pyfluid_amrex",
            "",
        )
    )


def _render_component(component: FieldComponent) -> str:
    return (
        "{" + ", ".join(
            (
                _cpp_string(component.name),
                _cpp_string(component.label),
                f"GridFieldCentering::{component.centering.value}",
                f"GridFieldSymmetryKind::{component.symmetry.value}",
            )
        ) + "}"
    )


def _render_components(field: GridField) -> str:
    return "{" + ", ".join(_render_component(c) for c in field.components) + "}"


def _render_grid_field(field: GridField) -> str:
    return "{" + ", ".join(
        (
            _cpp_string(field.name),
            _cpp_string(field.label),
            f"GridFieldValueKind::{field.value_kind.value}",
            _render_components(field),
            f"FieldRole::{field.role.value}",
            f"EvolutionFieldKind::{field.evolution_kind.value}",
            str(field.ghost_width),
            str(field.checkpoint).lower(),
            str(field.output).lower(),
        )
    ) + "}"


def _render_aux_field(field: GridField) -> str:
    return "{" + ", ".join(
        (
            f"AuxGridField::{field.aux_id}",
            _cpp_string(field.name),
            _cpp_string(field.label),
            _render_components(field),
            f"FieldRole::{field.role.value}",
            f"DiagnosticFieldKind::{field.diagnostic_kind.value}",
            f"EvolutionFieldKind::{field.evolution_kind.value}",
            str(field.requires_mhd).lower(),
            str(field.requires_solid_geometry).lower(),
            str(field.requires_gravity).lower(),
            str(field.min_dimension),
        )
    ) + "}"


def _render_field_vector(fields: tuple[GridField, ...]) -> str:
    return "{\n" + ",\n".join(f"         {_render_grid_field(field)}" for field in fields) + "\n      }"


def render_field_catalog_header() -> str:
    auxiliary_entries = ",\n".join(
        f"         {_render_aux_field(field)}" for field in AUXILIARY_FIELDS
    )
    newtonian_fields = _render_field_vector(FLUID_NEWTONIAN_FIELDS)
    relativistic_fields = _render_field_vector(FLUID_RELATIVISTIC_FIELDS)
    z4c_fields = _render_field_vector(Z4C_FIELDS)
    magnetic_field = _render_grid_field(MAGNETIC_FIELD)
    ct_magnetic_field = _render_grid_field(CT_MAGNETIC_FIELD)
    passive_scalar_field = _render_grid_field(PASSIVE_SCALAR_FIELD)
    return f"""// Generated by pyfluid_codegen.field_catalog. Do not edit.
#pragma once

#include <array>
#include <string>
#include <vector>

#include "pyfluid_amrex/fields.hpp"

namespace pyfluid_amrex::generated {{

inline auto auxiliary_grid_fields() -> std::array<AuxGridFieldInfo, {len(AUXILIARY_FIELDS)}> const&
{{
   static const std::array<AuxGridFieldInfo, {len(AUXILIARY_FIELDS)}> fields = {{{{
{auxiliary_entries}
   }}}};
   return fields;
}}

inline GridFieldInfo passive_scalar_grid_field(int index)
{{
   GridFieldInfo field = {passive_scalar_field};
   if (index > 0) {{
      const std::string suffix = "_" + std::to_string(index);
      field.name += suffix;
      field.label += "_{{" + std::to_string(index) + "}}";
      field.components.front().name += suffix;
      field.components.front().label += "_{{" + std::to_string(index) + "}}";
   }}
   return field;
}}

inline GridFieldSetInfo fluid_state_grid_fields(PhysicalSystem system, int passive_scalars)
{{
   GridFieldSetInfo set{{
      "fluid_state",
      "Fluid conserved state",
      EvolutionSector::Fluid,
      physical_system_is_relativistic(system)
         ? std::vector<GridFieldInfo>{relativistic_fields}
         : std::vector<GridFieldInfo>{newtonian_fields},
   }};
   if (physical_system_has_magnetic_field(system)) {{
      set.fields.push_back({magnetic_field});
   }}
   for (int index = 0; index < passive_scalars; ++index) {{
      set.fields.push_back(passive_scalar_grid_field(index));
   }}
   return set;
}}

inline GridFieldSetInfo const& z4c_state_grid_fields()
{{
   static const GridFieldSetInfo fields{{
      "spacetime_state",
      "Z4c spacetime state",
      EvolutionSector::Spacetime,
      std::vector<GridFieldInfo>{z4c_fields},
   }};
   return fields;
}}

inline GridFieldInfo const& ct_magnetic_grid_field()
{{
   static const GridFieldInfo field = {ct_magnetic_field};
   return field;
}}

}} // namespace pyfluid_amrex::generated
"""


def _latex_value(value: sp.Expr | Vector | Tensor) -> str:
    if isinstance(value, Vector):
        return r"\begin{pmatrix}" + r" \\ ".join(
            sp.latex(component) for component in value
        ) + r"\end{pmatrix}"
    if isinstance(value, Tensor):
        return r"\begin{pmatrix}" + r" \\ ".join(
            " & ".join(sp.latex(component) for component in row)
            for row in value.as_rows()
        ) + r"\end{pmatrix}"
    return sp.latex(value)


def render_equation_markdown() -> str:
    lines = [
        "# PyFluid Equation and Field Catalog",
        "",
        "This file is generated from the executable symbolic catalog. Do not edit it directly.",
        "",
        "## Evolution Systems",
        "",
    ]
    for system in fluid_equation_systems():
        lines.extend((f"### {system.title}", "", system.description, ""))
        for equation in system.equations:
            lines.extend(
                (
                    f"**{equation.identifier} — {equation.title}**",
                    "",
                    rf"$$\partial_t {equation.conserved_label} + \nabla\!\cdot\!\left({_latex_value(equation.flux)}\right) = {_latex_value(equation.source)}.$ $".replace(".$ $", ".$$") ,
                    "",
                )
            )

    lines.extend(("## Equations of State", ""))
    for eos in equation_of_state_records():
        qualifier = "barotropic" if eos.is_barotropic else "energy closing"
        lines.extend(
            (
                f"### {eos.title}",
                "",
                f"`{eos.identifier}` ({qualifier})",
                "",
                rf"$$P = {sp.latex(eos.pressure)}.$ $".replace(".$ $", ".$$") ,
                "",
                rf"$$u(P,\rho) = {sp.latex(eos.energy_from_pressure)}.$ $".replace(".$ $", ".$$") ,
                "",
                rf"$$c_s^2 = {sp.latex(eos.sound_speed_squared)}.$ $".replace(".$ $", ".$$") ,
                "",
            )
        )

    lines.extend(("## Grid Fields", ""))
    lines.append("| Field | Label | Components | Centering | Role | Sector |")
    lines.append("|---|---|---|---|---|---|")
    seen: set[tuple[str, str]] = set()
    for field in all_fields():
        key = (field.name, field.sector)
        if key in seen:
            continue
        seen.add(key)
        components = ", ".join(component.name for component in field.components)
        centerings = ", ".join(component.centering.value for component in field.components)
        lines.append(
            f"| `{field.name}` | ${field.label}$ | `{components}` | `{centerings}` | "
            f"`{field.role.value}` | `{field.sector}` |"
        )
    lines.append("")
    return "\n".join(lines)


def render_equation_latex() -> str:
    body = [
        r"\documentclass[11pt]{article}",
        r"\usepackage{amsmath,amssymb,booktabs,longtable,geometry}",
        r"\geometry{margin=1in}",
        r"\title{PyFluid Equation and Field Catalog}",
        r"\date{}",
        r"\begin{document}",
        r"\maketitle",
        r"Generated from the executable symbolic catalog. Do not edit directly.",
    ]
    for system in fluid_equation_systems():
        body.extend((rf"\section{{{system.title}}}", system.description))
        for equation in system.equations:
            body.extend(
                (
                    rf"\subsection*{{{equation.identifier}: {equation.title}}}",
                    r"\[",
                    rf"\partial_t {equation.conserved_label} + \nabla\cdot\left({_latex_value(equation.flux)}\right) = {_latex_value(equation.source)}.",
                    r"\]",
                )
            )
    body.append(r"\section{Equations of State}")
    for eos in equation_of_state_records():
        body.extend(
            (
                rf"\subsection*{{{eos.identifier}: {eos.title}}}",
                rf"\[P={sp.latex(eos.pressure)},\qquad u(P,\rho)={sp.latex(eos.energy_from_pressure)},\qquad c_s^2={sp.latex(eos.sound_speed_squared)}.\]",
            )
        )
    body.extend((r"\end{document}", ""))
    return "\n".join(body)


def render_field_catalog_json() -> str:
    fields = []
    component_labels: dict[str, str] = {}
    seen: set[tuple[str, str]] = set()
    for field in all_fields():
        key = (field.name, field.sector)
        if key in seen:
            continue
        seen.add(key)
        fields.append(
            {
                "name": field.name,
                "label": field.label,
                "value_kind": field.value_kind.value,
                "role": field.role.value,
                "diagnostic_kind": field.diagnostic_kind.value,
                "evolution_kind": field.evolution_kind.value,
                "sector": field.sector,
                "components": [
                    {
                        "name": component.name,
                        "label": component.label,
                        "centering": component.centering.value,
                        "symmetry": component.symmetry.value,
                    }
                    for component in field.components
                ],
            }
        )
        for component in field.components:
            previous = component_labels.setdefault(component.name, component.label)
            if previous != component.label:
                raise ValueError(
                    f"component {component.name} has inconsistent labels: "
                    f"{previous!r} != {component.label!r}"
                )
    diagnostics = [
        {
            "name": diagnostic.name,
            "label": diagnostic.label,
            "evaluation": diagnostic.evaluation.value,
            "dependencies": list(diagnostic.dependencies),
        }
        for diagnostic in (*RUNTIME_SCALAR_DIAGNOSTICS, *POSTPROCESS_DIAGNOSTICS)
    ]
    return json.dumps(
        {
            "schema_version": 1,
            "component_labels": component_labels,
            "fields": fields,
            "diagnostics": diagnostics,
        },
        indent=2,
        sort_keys=True,
    ) + "\n"


def render_diagnostic_catalog_header() -> str:
    names = ",\n".join(
        f"   {_cpp_string(diagnostic.name)}"
        for diagnostic in RUNTIME_SCALAR_DIAGNOSTICS
    )
    return f"""// Generated by pyfluid_codegen.diagnostic_catalog. Do not edit.
#pragma once

#include <array>
#include <string_view>

namespace pyfluid_amrex {{

inline constexpr std::array<std::string_view, {len(RUNTIME_SCALAR_DIAGNOSTICS)}> ScalarDiagnosticColumns = {{{{
{names}
}}}};

}} // namespace pyfluid_amrex
"""


def write_catalog(
    ids_header: Path,
    catalog_header: Path,
    diagnostic_header: Path,
    json_path: Path,
    markdown_path: Path,
    latex_path: Path,
) -> None:
    _write_if_changed(ids_header, render_field_ids_header())
    _write_if_changed(catalog_header, render_field_catalog_header())
    _write_if_changed(diagnostic_header, render_diagnostic_catalog_header())
    _write_if_changed(json_path, render_field_catalog_json())
    _write_if_changed(markdown_path, render_equation_markdown())
    _write_if_changed(latex_path, render_equation_latex())
