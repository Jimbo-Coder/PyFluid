def _flatten(fields: tuple[GridField, ...]) -> tuple[FieldComponent, ...]:
    return tuple(component for field in fields for component in field.components)


def render_field_ids_header() -> str:
    fluid_components = _flatten(FLUID_NEWTONIAN_FIELDS)
    magnetic_components = MAGNETIC_FIELD.components
    z4c_components = _flatten(Z4C_FIELDS)

    conserved_lines = [
        f"   {component.cpp_id} = {index},"
        for index, component in enumerate(fluid_components)
    ]
    conserved_lines.append(f"   NVAR_HYDRO = {len(fluid_components)},")
    conserved_lines.extend(
        f"   {component.cpp_id} = {len(fluid_components) + index},"
        for index, component in enumerate(magnetic_components)
    )
    conserved_lines.append(
        f"   NVAR_MHD = {len(fluid_components) + len(magnetic_components)},"
    )
    z4c_lines = [
        f"   {component.cpp_id} = {index},"
        for index, component in enumerate(z4c_components)
    ]
    z4c_lines.append(f"   Z4C_NUM_COMPONENTS = {len(z4c_components)},")
    aux_lines = [f"   {field.aux_id}," for field in AUXILIARY_FIELDS]
    aux_lines.append("   Unknown,")

    def component_array(name: str, fields: tuple[GridField, ...]) -> str:
        ids = ",\n".join(
            f"   {component.cpp_id}" for component in _flatten(fields)
        )
        return (
            f"inline constexpr int {name}[{len(_flatten(fields))}] = {{\n"
            f"{ids},\n"
            "};"
        )

    return "\n".join(
        (
            "// Generated by pyfluid_codegen.field_catalog. Do not edit.",
            "#pragma once",
            "",
            "namespace pyfluid_amrex {",
            "",
            "enum Conserved {",
            *conserved_lines,
            "};",
            "",
            "enum Z4cComponent : int {",
            *z4c_lines,
            "};",
            "",
            component_array("Z4C_GAMMA_TILDE_COMPONENTS", (Z4C_FIELDS[1],)),
            "",
            component_array("Z4C_A_TILDE_COMPONENTS", (Z4C_FIELDS[3],)),
            "",
            component_array("Z4C_GAMMA_TILDE_VECTOR_COMPONENTS", (Z4C_FIELDS[4],)),
            "",
            component_array("Z4C_SHIFT_COMPONENTS", (Z4C_FIELDS[7],)),
            "",
            "enum class AuxGridField {",
            *aux_lines,
            "};",
            "",
            "} // namespace pyfluid_amrex",
            "",
        )
    )


def _render_component(component: FieldComponent) -> str:
    return (
        "{" + ", ".join(
            (
                _cpp_string(component.name),
                _cpp_string(component.label),
                f"GridFieldCentering::{component.centering.value}",
                f"GridFieldSymmetryKind::{component.symmetry.value}",
            )
        ) + "}"
    )


def _render_components(field: GridField) -> str:
    return "{" + ", ".join(_render_component(c) for c in field.components) + "}"


def _render_grid_field(field: GridField) -> str:
    return "{" + ", ".join(
        (
            _cpp_string(field.name),
            _cpp_string(field.label),
            f"GridFieldValueKind::{field.value_kind.value}",
            _render_components(field),
            f"FieldRole::{field.role.value}",
            f"EvolutionFieldKind::{field.evolution_kind.value}",
            str(field.ghost_width),
            str(field.checkpoint).lower(),
            str(field.output).lower(),
        )
    ) + "}"


def _render_aux_field(field: GridField) -> str:
    return "{" + ", ".join(
        (
            f"AuxGridField::{field.aux_id}",
            _cpp_string(field.name),
            _cpp_string(field.label),
            _render_components(field),
            f"FieldRole::{field.role.value}",
            f"DiagnosticFieldKind::{field.diagnostic_kind.value}",
            f"EvolutionFieldKind::{field.evolution_kind.value}",
            str(field.requires_mhd).lower(),
            str(field.requires_solid_geometry).lower(),
            str(field.requires_gravity).lower(),
            str(field.min_dimension),
        )
    ) + "}"


def _render_field_vector(fields: tuple[GridField, ...]) -> str:
    return "{\n" + ",\n".join(f"         {_render_grid_field(field)}" for field in fields) + "\n      }"


